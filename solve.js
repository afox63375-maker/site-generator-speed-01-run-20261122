// A fast drop-in for makefun-site 1.0.0: run(input) returns, for one case's
// { site, templates, files }, the same output tree makefun-site's build
// returns, path by path and byte for byte. Written from the dialect spec in
// the kit's vendor README and the vendor code's observable behaviour, in this
// file's own structure. Speed comes from doing the same work with less of it:
// one pass over each body instead of lex-then-render, plain runs of text
// escaped in bulk instead of one character at a time, templates parsed once
// per case and rendered into joined part lists, and slugs cached per case.
//
// Nothing is kept between cases: every cache here is built inside run() and
// dropped with it, so each case is answered alone.

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

// ------------------------------------------------------------------ text

/** Code-unit order, never the locale's. */
const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

const ESC_RE = /[&<>"']/g;
const ESC_MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

/** `s` with & < > " ' escaped, in one pass. */
function esc(s) {
  return s.replace(ESC_RE, (c) => ESC_MAP[c]);
}

/** Whether the code unit is JavaScript whitespace (\s). */
function isWs(c) {
  return (
    c === 32 || c === 9 || c === 10 || c === 11 || c === 12 || c === 13 || c === 160 || c === 5760 ||
    (c >= 8192 && c <= 8202) || c === 8232 || c === 8233 || c === 8239 || c === 8287 || c === 12288 || c === 65279
  );
}

/** The runs of non-whitespace in `s`: its word count. */
function wordCount(s) {
  let n = 0;
  let inWord = false;
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    const ws =
      c === 32 || c === 9 || c === 10 || c === 11 || c === 12 || c === 13 || c === 160 || c === 5760 ||
      (c >= 8192 && c <= 8202) || c === 8232 || c === 8233 || c === 8239 || c === 8287 || c === 12288 || c === 65279;
    if (ws) inWord = false;
    else if (!inWord) {
      inWord = true;
      n++;
    }
  }
  return n;
}

const MARK_RE = /\p{M}/gu;

/** The slug of `text`, cached per case in `cache`. */
function slugOf(text, cache) {
  const hit = cache.get(text);
  if (hit !== undefined) return hit;
  // NFKD of plain ASCII is itself and ASCII holds no combining marks, so
  // the normalise-and-strip step is skipped for it.
  let plain = text;
  if (/[^\x00-\x7F]/.test(text)) plain = text.normalize('NFKD').replace(MARK_RE, '');
  let out = '';
  let gap = false;
  for (let i = 0; i < plain.length; i++) {
    const ch = plain[i];
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  let end = Math.min(out.length, 64);
  while (end > 0 && out[end - 1] === '-') end--;
  const slug = end === 0 ? 'untitled' : out.slice(0, end);
  cache.set(text, slug);
  return slug;
}

/** `slug` made unique against `taken` (and recorded there). */
function uniqueSlug(slug, taken) {
  if (!taken.has(slug)) {
    taken.add(slug);
    return slug;
  }
  let n = 2;
  for (;;) {
    const out = `${slug}-${n}`;
    if (!taken.has(out)) {
      taken.add(out);
      return out;
    }
    n++;
  }
}

/** A YYYY-MM-DD date in words, from the string alone. */
function longDate(date) {
  return `${Number(date.slice(8, 10))} ${MONTHS[Number(date.slice(5, 7)) - 1]} ${date.slice(0, 4)}`;
}

/** The directory of a "/"-separated path, "" at the root. */
function dirOf(path) {
  const k = path.lastIndexOf('/');
  return k === -1 ? '' : path.slice(0, k);
}

/** `rel` resolved from directory `dir`, or null when it climbs above the root. */
function resolveRel(dir, rel) {
  const parts = dir === '' ? [] : dir.split('/');
  for (const seg of rel.split('/')) {
    if (seg === '' || seg === '.') continue;
    if (seg === '..') {
      if (parts.length === 0) return null;
      parts.pop();
    } else parts.push(seg);
  }
  return parts.join('/');
}

// ------------------------------------------------------------ front matter

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function isKeyChar(c) {
  return (c >= 'a' && c <= 'z') || c === '_';
}

/** A quoted string's value, or its refusal reason. */
function quotedOf(raw) {
  if (raw.length < 2 || raw[raw.length - 1] !== '"') return { error: 'a quoted string is not closed' };
  let out = '';
  for (let i = 1; i < raw.length - 1; i++) {
    const c = raw[i];
    if (c === '\\') {
      if (i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
      const n = raw[i + 1];
      if (n !== '"' && n !== '\\') return { error: 'a quoted string holds an escape other than \\" or \\\\' };
      out += n;
      i++;
    } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
    else out += c;
  }
  return { value: out };
}

function hasBadTagChar(t) {
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (c === '"' || c === '[' || c === ']') return true;
  }
  return false;
}

function isName(s) {
  if (s.length === 0) return false;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '-')) return false;
  }
  return true;
}

function isSlugValue(s) {
  if (s.length === 0 || s.length > 64) return false;
  let i = 0;
  for (;;) {
    const c = s[i];
    if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9'))) return false;
    i++;
    while (i < s.length && (s[i] >= 'a' && s[i] <= 'z' || s[i] >= '0' && s[i] <= '9')) i++;
    if (i === s.length) return true;
    if (s[i] !== '-') return false;
    i++;
    if (i === s.length) return false;
  }
}

/** One key's value, or why it is refused. */
function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      if (raw[0] === '"') {
        const s = quotedOf(raw);
        return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
      }
      if (raw[0] === '[') return { error: `key "${key}": a bare string opens on [` };
      return { value: raw };
    }
    case 'date': {
      let ok = raw.length === 10 && raw[4] === '-' && raw[7] === '-';
      let y = 0;
      let mo = 0;
      let d = 0;
      if (ok) {
        for (let i = 0; i < 10; i++) {
          if (i === 4 || i === 7) continue;
          const c = raw.charCodeAt(i);
          if (c < 48 || c > 57) {
            ok = false;
            break;
          }
        }
        if (ok) {
          y = Number(raw.slice(0, 4));
          mo = Number(raw.slice(5, 7));
          d = Number(raw.slice(8, 10));
          if (y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) ok = false;
        }
      }
      return ok ? { value: raw } : { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
    }
    case 'tags': {
      if (raw[0] !== '[' || raw[raw.length - 1] !== ']') return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      for (const t of tags) {
        if (t === '' || hasBadTagChar(t)) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      }
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout':
      return isName(raw) ? { value: raw } : { error: 'key "layout": not a template name' };
    case 'slug':
      return isSlugValue(raw) ? { value: raw } : { error: 'key "slug": not a slug' };
    default:
      return { error: `unknown key "${key}"` };
  }
}

const KEYS = ['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary'];

/**
 * A source's front matter and body lines: { data, bodyLines }, or { error }
 * with the first reason it is refused. `text` has "\n" line ends.
 */
function parseFm(text) {
  const lines = text.split('\n');
  if (lines[0] !== '---') return { error: 'no front matter' };
  let close = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === '---') {
      close = i;
      break;
    }
  }
  if (close === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (let i = 1; i < close; i++) {
    const line = lines[i];
    let blank = true;
    for (let j = 0; j < line.length; j++) {
      const c = line.charCodeAt(j);
      if (c !== 32 && c !== 9) {
        blank = false;
        break;
      }
    }
    if (blank || line.charCodeAt(0) === 35) continue;
    let k = 0;
    while (k < line.length && isKeyChar(line[k])) k++;
    if (k === 0 || k >= line.length || line[k] !== ':') return { error: `line ${i + 1} is not "key: value"` };
    const key = line.slice(0, k);
    let raw;
    if (k === line.length - 1) raw = '';
    else if (line[k + 1] === ' ') raw = line.slice(k + 2);
    else return { error: `line ${i + 1} is not "key: value"` };
    let end = raw.length;
    while (end > 0 && (raw.charCodeAt(end - 1) === 32 || raw.charCodeAt(end - 1) === 9)) end--;
    raw = raw.slice(0, end);
    if (!KEYS.includes(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, bodyLines: lines.slice(close + 1) };
}

// ---------------------------------------------------------------- Markdown

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);
const WS_RE = /\s/;

/** Whether `line` holds only spaces and tabs. */
function isBlank(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** `line` with spaces and tabs dropped at either end. */
function trimST(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return line.slice(a, b);
}

/** A fence's language, or null when `line` does not open one. */
function fenceLang(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let i = 3;
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if (!((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45)) break;
    i++;
  }
  const lang = line.slice(3, i);
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return null;
    i++;
  }
  return lang;
}

/** Whether `line` closes a fence. */
function isFenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's level and text, or null. */
function headingOf(line) {
  let h = 0;
  while (h < line.length && line.charCodeAt(h) === 35) h++;
  if (h === 0 || h > 6 || h >= line.length) return null;
  const c = line.charCodeAt(h);
  if (c !== 32 && c !== 9) return null;
  let i = h;
  while (i < line.length && (line.charCodeAt(i) === 32 || line.charCodeAt(i) === 9)) i++;
  let end = line.length;
  while (end > i && (line.charCodeAt(end - 1) === 32 || line.charCodeAt(end - 1) === 9)) end--;
  if (end === i) return null;
  return { depth: h, text: line.slice(i, end) };
}

/** Whether `line` is a thematic break. */
function isHr(line) {
  if (line.length < 3) return false;
  const c0 = line.charCodeAt(0);
  if (c0 !== 45 && c0 !== 42) return false;
  if (line.charCodeAt(1) !== c0 || line.charCodeAt(2) !== c0) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** Whether `line` ends a paragraph. */
function endsPara(line) {
  return isBlank(line) || fenceLang(line) !== null || headingOf(line) !== null || isHr(line);
}

/** A bullet item's text, or null. */
function bulletOf(line) {
  const c = line.charCodeAt(0);
  if ((c === 45 || c === 42) && line.charCodeAt(1) === 32) return line.slice(2);
  return null;
}

/** An ordered item's number and text, or null. */
function orderedOf(line) {
  let i = 0;
  while (i < line.length && line.charCodeAt(i) >= 48 && line.charCodeAt(i) <= 57) i++;
  if (i === 0 || i > 9) return null;
  if (line.charCodeAt(i) !== 46 || line.charCodeAt(i + 1) !== 32) return null;
  return { num: line.slice(0, i), text: line.slice(i + 2) };
}

/** Whether `line` continues a list item (two spaces, then a non-space). */
function isContinued(line) {
  if (line.charCodeAt(0) !== 32 || line.charCodeAt(1) !== 32) return false;
  let i = 0;
  while (i < line.length && line.charCodeAt(i) === 32) i++;
  return i < line.length && !isWs(line.charCodeAt(i));
}

/** The first index from `from` where `s` holds `what` outside an escape, or -1. */
function findUnesc(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/** The characters that can start an inline construct. */
const SPECIAL = /[\\`*\[]/;

/**
 * `s` rendered inline into `parts`; `link(target)` is a link's href.
 * The scanner jumps from one construct to the next with a single search
 * instead of walking every character, plain runs are flushed through the
 * escaper in bulk, and nested content is appended straight into `parts`,
 * so a paragraph costs one escape pass per run instead of one call per
 * character and no throwaway strings per construct.
 */
function inlineTo(s, link, parts) {
  let i = 0;
  const n = s.length;
  while (i < n) {
    const rel = s.slice(i).search(SPECIAL);
    if (rel === -1) {
      parts.push(esc(s.slice(i)));
      return;
    }
    const j = i + rel;
    if (j > i) parts.push(esc(s.slice(i, j)));
    const c = s.charCodeAt(j);
    if (c === 92) {
      // Backslash: an escapable character after it is written as itself.
      const d = s[j + 1];
      if (j + 1 < n && ESCAPABLE.has(d)) {
        parts.push(d);
        i = j + 2;
      } else {
        parts.push(esc('\\'));
        i = j + 1;
      }
      continue;
    }
    if (c === 96) {
      const k = s.indexOf('`', j + 1);
      if (k > j + 1) {
        parts.push('<code>', esc(s.slice(j + 1, k)), '</code>');
        i = k + 1;
      } else {
        parts.push('`');
        i = j + 1;
      }
      continue;
    }
    if (c === 42) {
      if (s[j + 1] === '*') {
        const k = findUnesc(s, '**', j + 2);
        if (k > j + 2) {
          parts.push('<strong>');
          inlineTo(s.slice(j + 2, k), link, parts);
          parts.push('</strong>');
          i = k + 2;
        } else {
          parts.push('**');
          i = j + 2;
        }
        continue;
      }
      const k = findStar(s, j + 1);
      if (k > j + 1) {
        parts.push('<em>');
        inlineTo(s.slice(j + 1, k), link, parts);
        parts.push('</em>');
        i = k + 1;
      } else {
        parts.push('*');
        i = j + 1;
      }
      continue;
    }
    // A link: the first unescaped ] closes the text, ( must follow at once.
    const k = findUnesc(s, ']', j + 1);
    const m = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
    const target = m === -1 ? '' : s.slice(k + 2, m);
    if (target !== '' && !WS_RE.test(target)) {
      parts.push('<a href="', esc(link(target)), '">');
      inlineTo(s.slice(j + 1, k), link, parts);
      parts.push('</a>');
      i = m + 1;
    } else {
      parts.push('[');
      i = j + 1;
    }
  }
}

/**
 * `lines` rendered in one pass: its HTML, its table of contents (level 2 and 3
 * headings) and its excerpt (the first paragraph's inline HTML, or "").
 * `link` resolves a link target; `slugCache` is the case's slug cache.
 */
function renderMd(lines, link, slugCache) {
  const parts = [];
  const toc = [];
  const ids = new Set();
  let excerpt = null;
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const lang = fenceLang(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < lines.length && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      parts.push('<pre><code');
      if (lang !== '') parts.push(' class="language-', lang, '"');
      parts.push('>');
      for (const l of body) parts.push(esc(l), '\n');
      parts.push('</code></pre>\n');
      continue;
    }
    const hd = headingOf(line);
    if (hd !== null) {
      const id = uniqueSlug(slugOf(hd.text, slugCache), ids);
      const inner = [];
      inlineTo(hd.text, link, inner);
      const html = inner.join('');
      parts.push('<h', String(hd.depth), ' id="', id, '">', html, '</h', String(hd.depth), '>\n');
      if (hd.depth === 2 || hd.depth === 3) toc.push({ level: hd.depth, id, html });
      i++;
      continue;
    }
    if (isHr(line)) {
      parts.push('<hr>\n');
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      const body = [];
      while (i < lines.length && lines[i].charCodeAt(0) === 62) {
        const l = lines[i++];
        body.push(l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1));
      }
      const kept = [];
      for (const l of body) {
        const t = trimST(l);
        if (t !== '') kept.push(t);
      }
      if (kept.length === 0) parts.push('<blockquote>\n</blockquote>\n');
      else {
        parts.push('<blockquote>\n<p>');
        inlineTo(kept.join('\n'), link, parts);
        parts.push('</p>\n</blockquote>\n');
      }
      continue;
    }
    const bullet = bulletOf(line);
    const ordered = bullet === null ? orderedOf(line) : null;
    if (bullet !== null || ordered !== null) {
      const isOrdered = ordered !== null;
      const items = [];
      let startNum = 1;
      if (isOrdered) startNum = Number(ordered.num);
      while (i < lines.length) {
        const l = lines[i];
        const m = isOrdered ? orderedOf(l) : bulletOf(l);
        if (m !== null) {
          items.push([trimST(isOrdered ? m.text : m)]);
          i++;
        } else if (isContinued(l)) {
          items[items.length - 1].push(trimST(l));
          i++;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      if (isOrdered && startNum !== 1) parts.push('<ol start="', String(startNum), '">\n');
      else parts.push('<', tag, '>\n');
      for (const item of items) {
        parts.push('<li>');
        inlineTo(item.join('\n'), link, parts);
        parts.push('</li>\n');
      }
      parts.push('</', tag, '>\n');
      continue;
    }
    const body = [trimST(line)];
    i++;
    while (i < lines.length && !endsPara(lines[i])) body.push(trimST(lines[i++]));
    if (excerpt === null) {
      // The first paragraph's HTML is also the excerpt, so keep it as a string.
      const inner = [];
      inlineTo(body.join('\n'), link, inner);
      excerpt = inner.join('');
      parts.push('<p>', excerpt, '</p>\n');
    } else {
      parts.push('<p>');
      inlineTo(body.join('\n'), link, parts);
      parts.push('</p>\n');
    }
  }
  return { html: parts.join(''), toc, excerpt: excerpt ?? '' };
}

